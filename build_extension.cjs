// Builds the extension payload from the mod source, the same way the site build splices
// mod5.js into the game bundle:
//   - `__PT_TRACK_NAMES__` / `__PT_OFFICIAL__` are filled from trackmaps.txt
//   - `c`, `x` and `n` (three's Vector3, the game's camera controller and the webpack
//     require on the site build) are bound to the stand-ins compat.js and gameapi.js install
//   - the render hook is exposed so compat.js can attach it to the live renderer
//   node build_extension.cjs
const fs = require("node:fs");
const path = require("node:path");

const ROOT = __dirname;
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

const mod = read("mod5.js");
const maps = read("trackmaps.txt").trim().split("\n");

function table(name) {
  const head = "const " + name + "=";
  const line = maps.find((l) => l.startsWith(head));
  if (!line) throw new Error("trackmaps.txt: missing " + head);
  const expr = line.slice(head.length).replace(/;\s*$/, "");
  if (!expr.startsWith("{")) throw new Error("trackmaps.txt: " + name + " is not an object literal");
  return expr;
}

let out = mod;
for (const name of ["TRACK_NAMES", "OFFICIAL"]) {
  const token = "__PT_" + name + "__";
  if (!out.includes(token)) throw new Error("mod5.js: missing placeholder " + token);
  out = out.split(token).join(table(name));
}

const left = out.match(/__PT_[A-Z_]+__/);
if (left) throw new Error("unfilled placeholder left in output: " + left[0]);

const makeRenderer = "window.__ptMakeRenderer=function(o){";
if (!out.includes(makeRenderer)) throw new Error("mod5.js: renderer hook not found");
out = out.replace(
  makeRenderer,
  "window.__ptHookRenderer=hookRenderer;" + makeRenderer,
);

const header =
  "// Generated by build_extension.cjs from mod5.js + trackmaps.txt - do not edit.\n" +
  "// `c`, `x` and `n` are the names the site build gets from the game's module scope.\n" +
  "var c=window.__ptCompat&&window.__ptCompat.three,x=window.__ptCompat&&window.__ptCompat.camCtl,n=window.__ptRequire;\n" +
  "if(!c||!x||!n)throw new Error(\"PolyMod: compat.js and gameapi.js must load first\");\n";

const dest = path.join(ROOT, "extension", "src", "mod.js");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, header + out);
console.log("extension/src/mod.js written: " + fs.statSync(dest).size + " bytes");
